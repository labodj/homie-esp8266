"""Build the offline page as a deterministic gzip asset and restrictive CSP."""

import argparse
import base64
import gzip
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/Homie/Boot/ConfigUi.html"
OUTPUT = SOURCE.with_suffix(".hpp")
MAX_UI_BYTES = 7 * 1024


def main() -> None:
    """Generate or verify the page bytes and inline-content hashes."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = SOURCE.read_bytes()
    hashes = {}
    for tag in ("script", "style"):
        contents = re.findall(
            rb"<" + tag.encode() + rb">(.*?)</" + tag.encode() + rb">", source, re.DOTALL
        )
        if len(contents) != 1:
            parser.error(f"Expected one inline {tag}")
        hashes[tag] = base64.b64encode(hashlib.sha256(contents[0]).digest()).decode()
    policy = (
        "default-src 'none'; connect-src 'self'; base-uri 'none'; "
        "form-action 'self'; frame-ancestors 'none'; "
        f"script-src 'sha256-{hashes['script']}'; style-src 'sha256-{hashes['style']}'"
    )
    if args.check:
        text = OUTPUT.read_text()
        asset = bytes(int(value, 16) for value in re.findall(r"0x([0-9a-f]{2})", text))
        # Compare content, not zlib output, which can vary across toolchain versions.
        if gzip.decompress(asset) != source or f'"{policy}"' not in text:
            parser.error("Stale UI asset; run python tools/generate_config_ui.py")
    else:
        encoded = bytearray(gzip.compress(source, compresslevel=9, mtime=0))
        encoded[9] = 255  # Stable gzip OS marker across Python versions.
        asset = bytes(encoded)
        rows = [
            "  " + ", ".join(f"0x{byte:02x}" for byte in asset[i : i + 16])
            for i in range(0, len(asset), 16)
        ]
        OUTPUT.write_text(
            "// Generated by tools/generate_config_ui.py; edit ConfigUi.html.\n"
            "#pragma once\nnamespace HomieInternals {\n"
            "const uint8_t CONFIG_UI[] PROGMEM = {\n" + ",\n".join(rows) + "\n};\n"
            f'const char CONFIG_UI_CSP[] PROGMEM = "{policy}";\n'
            "}  // namespace HomieInternals\n"
        )
    if len(asset) > MAX_UI_BYTES:
        parser.error("UI exceeds its 7 KiB transfer budget")
    sys.stdout.write(f"UI: {len(source)} bytes source, {len(asset)} bytes gzip\n")


if __name__ == "__main__":
    main()
